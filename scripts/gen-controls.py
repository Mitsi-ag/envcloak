#!/usr/bin/env python3
"""Generates crates/envcloak-spend/src/controls/table.rs from
crates/envcloak-spend/src/controls/controls.toml and checks that its five
control rows match the table in docs/SPEC.md §2a-bis byte for byte (M4-05,
D4-07, D4-28, gate s7).

Run from the repository root after editing controls.toml:

    python3 scripts/gen-controls.py            # rewrite table.rs
    python3 scripts/gen-controls.py --check    # exit 1 if stale or SPEC mismatches
"""

import os
import sys
import tomllib

TOML_PATH = os.path.join("crates", "envcloak-spend", "src", "controls", "controls.toml")
SPEC_PATH = os.path.join("docs", "SPEC.md")
OUT_PATH = os.path.join("crates", "envcloak-spend", "src", "controls", "table.rs")

EXPECTED_IDS = [
    ("provider_cap", "Control::ProviderCap"),
    ("proxy_gate", "Control::ProxyGate"),
    ("auto_key_disable", "Control::AutoKeyDisable"),
    ("card_auth_limit", "Control::CardAuthLimit"),
    ("alert_only", "Control::AlertOnly"),
]


def rust_str(s: str) -> str:
    for ch in s:
        if ord(ch) < 0x20 or ord(ch) == 0x7F:
            sys.exit(f"control string contains control character U+{ord(ch):04X}")
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def parse_spec_table(spec_text: str):
    lines = spec_text.splitlines()
    header = "| Control | Enforced by | Stops | Does not stop |"
    try:
        idx = next(i for i, line in enumerate(lines) if line.strip() == header)
    except StopIteration:
        sys.exit(f"{SPEC_PATH}: missing '{header}' table header in §2a-bis")

    if idx + 1 >= len(lines) or not lines[idx + 1].strip().startswith("|---"):
        sys.exit(f"{SPEC_PATH}: malformed separator row after '{header}'")

    rows = []
    for line in lines[idx + 2 :]:
        s = line.strip()
        if not s.startswith("|"):
            break
        cells = [c.strip() for c in s.strip("|").split("|")]
        if len(cells) != 4:
            sys.exit(f"{SPEC_PATH}: expected 4 columns in control row, got {len(cells)}: {s}")
        rows.append(tuple(cells))
    return rows


def load_and_verify(root: str):
    toml_file = os.path.join(root, TOML_PATH)
    spec_file = os.path.join(root, SPEC_PATH)

    with open(toml_file, "rb") as f:
        raw = f.read()
    if b"\r" in raw:
        sys.exit(f"{TOML_PATH}: use LF line endings")
    data = tomllib.loads(raw.decode("utf-8"))

    controls = data.get("control", [])
    if len(controls) != len(EXPECTED_IDS):
        sys.exit(
            f"{TOML_PATH}: expected {len(EXPECTED_IDS)} [[control]] entries, found {len(controls)}"
        )

    for idx, (ctrl, (expected_id, _)) in enumerate(zip(controls, EXPECTED_IDS)):
        actual_id = ctrl.get("id")
        if actual_id != expected_id:
            sys.exit(
                f"{TOML_PATH}: control #{idx + 1} has id {actual_id!r}, expected {expected_id!r}"
            )
        for key in ("name", "enforced_by", "stops", "does_not_stop"):
            val = ctrl.get(key)
            if not isinstance(val, str) or not val.strip():
                sys.exit(f"{TOML_PATH}: control {actual_id!r} missing non-empty {key!r}")

    alert_dns = controls[4]["does_not_stop"]
    required_suffix = "and is not evaluated while the vault is locked or the machine sleeps"
    if not alert_dns.endswith(required_suffix):
        sys.exit(
            f"{TOML_PATH}: alert_only.does_not_stop must end with {required_suffix!r}"
        )

    with open(spec_file, encoding="utf-8") as f:
        spec_rows = parse_spec_table(f.read())

    if len(spec_rows) != len(controls):
        sys.exit(
            f"{SPEC_PATH}: §2a-bis table has {len(spec_rows)} rows, expected {len(controls)}"
        )

    for ctrl, spec_row in zip(controls, spec_rows):
        toml_row = (
            ctrl["name"],
            ctrl["enforced_by"],
            ctrl["stops"],
            ctrl["does_not_stop"],
        )
        if toml_row != spec_row:
            sys.exit(
                f"control row mismatch for {ctrl['id']!r}:\n"
                f"  controls.toml: {toml_row!r}\n"
                f"  docs/SPEC.md : {spec_row!r}"
            )

    providers = data.get("provider", [])
    if not providers:
        sys.exit(f"{TOML_PATH}: expected at least one [[provider]] entry")
    for p in providers:
        for key in ("id", "display_name", "cap_scope", "stated_lag", "source"):
            val = p.get(key)
            if not isinstance(val, str) or not val.strip():
                sys.exit(f"{TOML_PATH}: provider entry missing non-empty {key!r}")

    return controls, providers


def render(controls, providers) -> str:
    lines = [
        "//! Static five-control table and per-provider lag metadata (`SPEC §2a-bis`,",
        "//! `D4-07`, `D4-28`, gate `s7`).",
        "//!",
        "//! Generated by `scripts/gen-controls.py` from",
        "//! `crates/envcloak-spend/src/controls/controls.toml`. Do not edit by hand.",
        "",
        "use super::Control;",
        "",
        "/// One static row of the five-control table from `SPEC §2a-bis`.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct ControlTableRow {",
        "    /// Closed control enum variant.",
        "    pub control: Control,",
        "    /// Canonical control name in `SPEC §2a-bis`.",
        "    pub name: &'static str,",
        "    /// Base `Enforced by` cell in `SPEC §2a-bis`.",
        "    pub enforced_by: &'static str,",
        "    /// Base `Stops` cell in `SPEC §2a-bis`.",
        "    pub stops: &'static str,",
        "    /// Base `Does not stop` cell in `SPEC §2a-bis`.",
        "    pub does_not_stop: &'static str,",
        "}",
        "",
        "/// Per-provider cap scope and stated lag from `m4/research.md` §3.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct ProviderControlNote {",
        "    /// Lowercase provider slug (`openai`, `openrouter`, `gemini`, ...).",
        "    pub id: &'static str,",
        "    /// Display name used in control headlines and lag notes.",
        "    pub display_name: &'static str,",
        "    /// Documented cap scope for this provider.",
        "    pub cap_scope: &'static str,",
        "    /// Provider-stated enforcement lag or behaviour.",
        "    pub stated_lag: &'static str,",
        "    /// Citation in vendor documentation.",
        "    pub source: &'static str,",
        "}",
        "",
        "/// All five controls in `SPEC §2a-bis` order.",
        "pub static CONTROL_TABLE: [ControlTableRow; 5] = [",
    ]

    for ctrl, (_, variant) in zip(controls, EXPECTED_IDS):
        lines.extend(
            [
                "    ControlTableRow {",
                f"        control: {variant},",
                f"        name: {rust_str(ctrl['name'])},",
                f"        enforced_by: {rust_str(ctrl['enforced_by'])},",
                f"        stops: {rust_str(ctrl['stops'])},",
                f"        does_not_stop: {rust_str(ctrl['does_not_stop'])},",
                "    },",
            ]
        )

    lines.extend(
        [
            "];",
            "",
            "/// Per-provider cap scope and stated lag notes (`m4/research.md` §3).",
            f"pub static PROVIDER_CONTROL_NOTES: [ProviderControlNote; {len(providers)}] = [",
        ]
    )

    for p in providers:
        lines.extend(
            [
                "    ProviderControlNote {",
                f"        id: {rust_str(p['id'])},",
                f"        display_name: {rust_str(p['display_name'])},",
                f"        cap_scope: {rust_str(p['cap_scope'])},",
                f"        stated_lag: {rust_str(p['stated_lag'])},",
                f"        source: {rust_str(p['source'])},",
                "    },",
            ]
        )

    lines.extend(
        [
            "];",
            "",
            "/// Looks up the static `SPEC §2a-bis` row for `control`.",
            "#[must_use]",
            "pub const fn row_for(control: Control) -> &'static ControlTableRow {",
            "    match control {",
            "        Control::ProviderCap => &CONTROL_TABLE[0],",
            "        Control::ProxyGate => &CONTROL_TABLE[1],",
            "        Control::AutoKeyDisable => &CONTROL_TABLE[2],",
            "        Control::CardAuthLimit => &CONTROL_TABLE[3],",
            "        Control::AlertOnly => &CONTROL_TABLE[4],",
            "    }",
            "}",
            "",
            "/// Looks up the provider lag and scope note for `provider_id`.",
            "#[must_use]",
            "pub fn provider_note(provider_id: &str) -> Option<&'static ProviderControlNote> {",
            "    PROVIDER_CONTROL_NOTES",
            "        .iter()",
            "        .find(|note| note.id.eq_ignore_ascii_case(provider_id))",
            "}",
            "",
        ]
    )

    return "\n".join(lines)


def main():
    args = sys.argv[1:]
    check = False
    root = "."
    i = 0
    while i < len(args):
        if args[i] == "--check":
            check = True
            i += 1
        elif args[i] == "--root" and i + 1 < len(args):
            root = args[i + 1]
            i += 2
        else:
            sys.exit("usage: gen-controls.py [--check] [--root <dir>]")

    controls, providers = load_and_verify(root)
    want = render(controls, providers)
    out_file = os.path.join(root, OUT_PATH)

    if check:
        try:
            with open(out_file, encoding="utf-8") as f:
                have = f.read()
        except OSError:
            have = None
        if have != want:
            sys.exit(f"{OUT_PATH} is stale: run python3 scripts/gen-controls.py")
        return

    with open(out_file, "w", encoding="utf-8") as f:
        f.write(want)


if __name__ == "__main__":
    main()
